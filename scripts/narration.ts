/**
 * Generates the standalone narration script from the walkthrough.
 *
 * ## Why this is generated rather than written
 *
 * A recording script and an application are two artefacts that describe the
 * same thing, and the ordinary fate of such a pair is to drift. Somebody edits
 * a caption in `script.ts` three months from now; the document a voice artist
 * was sent still says the old line; the recording that comes back no longer
 * matches the picture, and nobody notices until it is on the landing page.
 *
 * So the document has no independent existence. `src/components/demo/script.ts`
 * is the source, this emits the rest, and `npm run narration:check` fails the
 * build if the committed file has fallen behind. The generated file is checked
 * in deliberately: a voice artist, a translator or a stakeholder should be able
 * to read it on the repository page without installing Node.
 *
 * ## What a voice artist actually needs
 *
 * Three things this produces, which a bare list of sentences does not:
 *
 *  - **A start timecode per line**, so a recorded take can be cut against the
 *    picture rather than guessed at.
 *  - **A word budget and target rate per line**, so the person reading knows
 *    before they start whether they are being asked to hurry. A line that
 *    cannot be delivered at the marked rate is a script defect, not a
 *    performance problem.
 *  - **A clean block containing nothing but the spoken words.** Markdown pasted
 *    into a text-to-speech engine is read aloud as markdown — "hash hash
 *    Locora, star star" — so the copy-paste section carries no formatting at
 *    all.
 *
 * No paid service is involved anywhere in this, and nothing in the application
 * waits on the result. The walkthrough plays, captioned, with a transcript,
 * whether or not audio is ever recorded.
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import {
  SCENES,
  SPOKEN_WPS_MAX,
  SPOKEN_WPS_MIN,
  TOTAL_DURATION_MS,
  TOTAL_NARRATION_WORDS,
  formatTimecode,
  narrationRateWps,
  narrationWordCount,
  sceneStartMs,
} from "../src/components/demo/script";

/**
 * Resolved from the working directory rather than from `import.meta.dirname`,
 * which tsx does not provide here: it transpiles these scripts to CommonJS, and
 * `import.meta` does not exist in that output. Every npm script in this project
 * runs from the repository root, which is what makes this equivalent.
 */
const OUTPUT = resolve(process.cwd(), "docs", "NARRATION.md");

/** `0:11.5` — tenths, because a cut point half a second out is audible. */
function preciseTimecode(ms: number): string {
  const totalSeconds = ms / 1000;
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = totalSeconds % 60;
  return `${minutes}:${seconds.toFixed(1).padStart(4, "0")}`;
}

function render(): string {
  const wpm = Math.round((TOTAL_NARRATION_WORDS / (TOTAL_DURATION_MS / 1000)) * 60);

  const lines: string[] = [];

  lines.push("# Locora — walkthrough narration");
  lines.push("");
  lines.push(
    "<!-- Generated by `npm run narration`. Do not edit this file by hand: the",
    "     source is src/components/demo/script.ts, and any change made here",
    "     will be overwritten and will fail `npm run narration:check`. -->",
  );
  lines.push("");
  lines.push(
    `**Runtime ${formatTimecode(TOTAL_DURATION_MS)} · ${TOTAL_NARRATION_WORDS} words · ${wpm} words per minute · ${SCENES.length} chapters**`,
  );
  lines.push("");
  lines.push(
    "This is the spoken script for the product walkthrough on the Locora landing",
    "page. It is also the on-screen transcript, deliberately: a viewer who cannot",
    "hear the audio reads the same account of the product as one who can.",
  );
  lines.push("");

  // --- Direction -----------------------------------------------------------
  lines.push("## Direction");
  lines.push("");
  lines.push(
    "Calm, warm and unhurried. This is a product about missing people, and the",
    "register that suits it is the one a good clinician or a good caseworker uses:",
    "plain, steady, and confident without being brisk. Read it as though",
    "explaining something important to one person, not as though announcing it to",
    "a room.",
  );
  lines.push("");
  lines.push("Specifically, avoid:");
  lines.push("");
  lines.push(
    "- **Advertising lift** — the rising, bright delivery of a commercial. Locora",
    "  is not selling anything, and enthusiasm here reads as insensitivity.",
    "- **Portentous slowness.** Solemnity laid on thickly is its own kind of",
    "  dishonesty, and it makes a two-minute piece feel like five.",
    "- **Emphasis on the technology.** Where a line names something the software",
    "  does, the weight belongs on the human consequence, not the mechanism.",
  );
  lines.push("");
  lines.push(
    `Every line below is budgeted between ${SPOKEN_WPS_MIN} and ${SPOKEN_WPS_MAX} words per second`,
    `(${Math.round(SPOKEN_WPS_MIN * 60)}–${Math.round(SPOKEN_WPS_MAX * 60)} words per minute) and checked automatically. If a line`,
    "feels rushed at the marked rate, the script is wrong and should be shortened",
    "in `src/components/demo/script.ts` — do not compress the delivery to fit.",
  );
  lines.push("");
  lines.push(
    "Leave the natural pause between chapters rather than running lines together;",
    "each one begins on a scene change and has room for a breath.",
  );
  lines.push("");

  // --- Timed script --------------------------------------------------------
  lines.push("## Timed script");
  lines.push("");

  for (const [index, scene] of SCENES.entries()) {
    const start = sceneStartMs(index);
    const end = start + scene.durationMs;
    const words = narrationWordCount(scene);
    const rate = narrationRateWps(scene);

    lines.push(`### ${index + 1}. ${scene.chapter}`);
    lines.push("");
    lines.push(
      `\`${preciseTimecode(start)} – ${preciseTimecode(end)}\` · ` +
        `${(scene.durationMs / 1000).toFixed(1)}s · ${words} words · ${rate.toFixed(2)} words/sec`,
    );
    lines.push("");
    lines.push(`> ${scene.narration}`);
    lines.push("");
    lines.push(`*On screen:* ${scene.caption}`);
    lines.push("");
  }

  // --- Copy-paste block ----------------------------------------------------
  lines.push("## For a text-to-speech tool");
  lines.push("");
  lines.push(
    "Everything between the two markers is the complete narration and nothing",
    "else — no headings, no timecodes, no formatting characters. Paste it whole",
    "into any voice generator. Chapters are separated by a blank line, which most",
    "engines render as a short pause; if yours does not, record the chapters",
    "separately using the timecodes above.",
  );
  lines.push("");
  lines.push("```text");
  lines.push("--- BEGIN NARRATION ---");
  lines.push("");
  for (const scene of SCENES) {
    lines.push(scene.narration);
    lines.push("");
  }
  lines.push("--- END NARRATION ---");
  lines.push("```");
  lines.push("");

  // --- Production notes ----------------------------------------------------
  lines.push("## If audio is produced");
  lines.push("");
  lines.push(
    "The walkthrough is a rendered interface rather than a video file, so audio is",
    "an addition to it, not a replacement for it. Whatever is recorded, three",
    "things have to remain true:",
  );
  lines.push("");
  lines.push(
    "1. **Nothing autoplays with sound.** The walkthrough is on the landing page,",
    "   which someone may open in a public place in the middle of an emergency.",
    "2. **The captions stay.** They are not a fallback for missing audio; they are",
    "   the equal path through the same content.",
    "3. **A visitor who has asked for reduced motion still gets the storyboard.**",
    "   That path renders no timeline at all, so it has nothing to synchronise to.",
  );
  lines.push("");
  lines.push(
    "Any tool capable of exporting a single audio file is sufficient — including",
    "the free tiers of the common browser-based generators, and the speech",
    "synthesis built into macOS, Windows and most Linux distributions. Locora",
    "takes no dependency on any of them, and none is required for the product to",
    "work.",
  );
  lines.push("");

  return lines.join("\n");
}

async function main(): Promise<void> {
  const content = render();

  // `--check` is what CI runs. It asserts the committed file matches what the
  // source would generate, which is the only thing that keeps the two honest.
  if (process.argv.includes("--check")) {
    const existing = await readFile(OUTPUT, "utf8").catch(() => null);

    if (existing !== content) {
      console.error(
        "docs/NARRATION.md is out of date with src/components/demo/script.ts.\n" +
          "  Run `npm run narration` and commit the result.",
      );
      process.exitCode = 1;
      return;
    }

    console.log("[narration] docs/NARRATION.md matches the walkthrough script");
    return;
  }

  await writeFile(OUTPUT, content, "utf8");
  console.log(
    `[narration] wrote docs/NARRATION.md — ${TOTAL_NARRATION_WORDS} words, ${formatTimecode(TOTAL_DURATION_MS)}`,
  );
}

main().catch((error: unknown) => {
  console.error(
    `[narration] failed
${error instanceof Error ? error.message : String(error)}`,
  );
  process.exit(1);
});
